let a = 3;

//...

a = 10; // A variável a agora tem o valor 10

//...

console.log(a); // Imprime o valor da variável a, que é 10

//Quando queremos mudar o valor utilizamos o símbolo de atribuição (=) para atribuir um novo valor à variável. No exemplo acima, a variável a foi inicialmente declarada com o valor 3, mas depois foi alterada para 10.

a = a +10; // A variável a agora tem o valor 20

console.log(a); // Imprime o valor da variável a, que é 20

//Quando queremos que ela nunca mude utilizamos a função const, como no exemplo abaixo:
const b = 5; // A variável b é constante e não pode ser alterada
console.log(b); // Imprime o valor da variável b, que é 5