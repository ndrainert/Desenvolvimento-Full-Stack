//O que significa cada sentença de código?
console.log("Caneta"); // Imprime a string "Caneta"
console.log(10); // Imprime o número 10
console.log(6.4); // Imprime o número 6.4
console.log(1.5); // Imprime o número 1.5
console.log(7.9); // Imprime o número 7.9

//Não faz sentido adivinhar o que cada sentença de código significa, por isso utilizamos dados variáveis.

var nome = "Caneta"; // Variável do tipo string
var quantidade = 10; // Variável do tipo number
var preco = 6.4;    // Variável do tipo number
var imposto = 1.5; // Variável do tipo number
var precoFinal = preco + imposto; // Variável do tipo number

//Na prática, cada sentença de código é uma instrução que o computador deve executar. As variáveis armazenam dados que podem ser manipulados e utilizados em diferentes partes do programa.
console.log(nome); // Imprime o valor da variável nome
console.log(quantidade); // Imprime o valor da variável quantidade
console.log(preco); // Imprime o valor da variável preco
console.log(imposto); // Imprime o valor da variável imposto
console.log(precoFinal); // Imprime o valor da variável precoFinal