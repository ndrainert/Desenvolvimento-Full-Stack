//Tipos de dados básicos em JavaScript
//Em JavaScript, existem alguns tipos de dados básicos que podemos utilizar para armazenar informações. Alguns exemplos são:
// number: para armazenar números
// string: para armazenar textos
// boolean: para armazenar valores lógicos (true ou false)
// undefined: para armazenar valores indefinidos
// null: para armazenar valores nulos

//Exemplos de cada tipo de dado básico em JavaScript:
let numero = 10; // number
let texto = "Olá, mundo!"; // string
let verdadeiro = true; // boolean
let indefinido; // undefined
let nulo = null; // null

//utilizando o console.log() para imprimir os valores das variáveis no console:
console.log(numero); // Imprime o valor da variável numero
console.log(texto); // Imprime o valor da variável texto
console.log(verdadeiro); // Imprime o valor da variável verdadeiro
console.log(indefinido); // Imprime o valor da variável indefinido
console.log(nulo); // Imprime o valor da variável nulo

//Usando a funcionalidade typeof para verificar o tipo de dado de cada variável:
console.log(typeof numero); // Imprime "number"
console.log(typeof texto); // Imprime "string"
console.log(typeof verdadeiro); // Imprime "boolean"
console.log(typeof indefinido); // Imprime "undefined"
console.log(typeof nulo); // Imprime "object" (isso é um comportamento conhecido do JavaScript, onde null é considerado um objeto)